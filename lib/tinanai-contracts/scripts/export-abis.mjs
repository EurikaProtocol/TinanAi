import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import hre from 'hardhat';

const root = new URL('../', import.meta.url);
await mkdir(new URL('abi/', root), { recursive: true });
await mkdir(new URL('src/', root), { recursive: true });
const exports = [];
for (const name of ['TinanAiToken', 'TinanAiCore']) {
  const artifact = await hre.artifacts.readArtifact(name);
  if (name === 'TinanAiToken') {
    const buildId = await hre.artifacts.getBuildInfoId(name);
    const buildPath = buildId && await hre.artifacts.getBuildInfoPath(buildId);
    if (!buildPath) throw new Error('Token compiler provenance is unavailable.');
    const build = JSON.parse(await readFile(buildPath, 'utf8'));
    const source = await readFile(new URL('contracts/TinanAiToken.sol', root), 'utf8');
    const compiledSource = Object.entries(build.input.sources).find(([key]) => key.endsWith('/contracts/TinanAiToken.sol'))?.[1]?.content;
    if (compiledSource !== source) throw new Error('Compiled Token source differs from the reviewed source.');
    const provenance = { sourceSha256: createHash('sha256').update(source).digest('hex'), compilerVersion: build.solcVersion,
      optimizer: build.input.settings.optimizer, evmVersion: build.input.settings.evmVersion };
    await writeFile(new URL('src/generated-token-artifact.ts', root),
      `// Generated from the existing TinanAiToken by scripts/export-abis.mjs.\nexport const tokenBuild = ${JSON.stringify(provenance)} as const;\nexport const tokenArtifact = ${JSON.stringify({ abi: artifact.abi, bytecode: artifact.bytecode, deployedBytecode: artifact.deployedBytecode })} as const;\n`);
  }
  const abiJson = JSON.stringify(artifact.abi, null, 2);
  await writeFile(new URL(`abi/${name}.json`, root), `${abiJson}\n`);
  exports.push(`export const ${name === 'TinanAiToken' ? 'tinanAiTokenAbi' : 'tinanAiCoreAbi'} = ${abiJson} as const;`);
}
await writeFile(
  new URL('src/generated-abis.ts', root),
  `// Generated by scripts/export-abis.mjs; do not edit by hand.\n${exports.join('\n\n')}\n`,
);
console.log(`Exported Token/Core JSON and TypeScript ABIs to ${fileURLToPath(root)}.`);
